"""Generate ``frontend/src/services/types.ts`` from ``autotune_studio/contracts.py``.

Uses Pydantic JSON schemas; supports the subset of schema features used by the contracts
(objects, arrays, enums, const/literals, anyOf with null, dict[str, Any]).
"""

from __future__ import annotations

import enum
import json
import inspect
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic import BaseModel  # noqa: E402

from autotune_studio import contracts  # noqa: E402

OUT = ROOT / "frontend" / "src" / "services" / "types.ts"


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in schema["enum"])
    if "anyOf" in schema:
        parts = [ts_type(s) for s in schema["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    if t == "object":
        add = schema.get("additionalProperties")
        if isinstance(add, dict) and add:
            return f"Record<string, {ts_type(add)}>"
        return "Record<string, unknown>"
    return "unknown"


def render_model(name: str, schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return f"export type {name} = {ts_type(schema)};\n"
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, ps in schema.get("properties", {}).items():
        opt = "" if prop in required else "?"
        doc = ps.get("description")
        if doc:
            lines.append(f"  /** {doc} */")
        lines.append(f"  {prop}{opt}: {ts_type(ps)};")
    lines.append("}\n")
    return "\n".join(lines)


def main() -> int:
    defs: dict[str, dict[str, Any]] = {}
    for name, obj in inspect.getmembers(contracts):
        if inspect.isclass(obj) and obj.__module__ == contracts.__name__:
            if issubclass(obj, BaseModel) and not name.startswith("_"):
                sch = obj.model_json_schema(mode="serialization")
                for dname, d in sch.pop("$defs", {}).items():
                    defs.setdefault(dname, d)
                defs[name] = sch
            elif issubclass(obj, enum.Enum):
                defs[name] = {"enum": [m.value for m in obj]}
    out = [
        "// AUTO-GENERATED by scripts/gen_ts_types.py from autotune_studio/contracts.py. Do not edit.\n",
    ]
    for name in sorted(defs):
        out.append(render_model(name, defs[name]))
    codes = {k: v for k, v in vars(contracts.ErrorCode).items() if not k.startswith("_")}
    out.append("export const ErrorCode = {")
    out.extend(f'  {k}: "{v}",' for k, v in codes.items())
    out.append("} as const;\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(defs)} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
